import { Brygada_1918, Great_Vibes } from "next/font/google";
import "./globals.css";
import Navbar from "@/components/nav";
import Footer from "@/components/footer/footer";
import { TooltipProvider } from "@/components/ui/tooltip";
import { GoogleTagManager } from '@next/third-parties/google'; 
import { Toaster } from "@/components/ui/sonner"; 
import { connectDB } from "@/lib/mongoose";
import Regulation from "@/lib/models/regulation";
const geistPrimary = Brygada_1918({
  variable: "--font-brygada-1918",
  subsets: ["latin"],
  weight: ["400", "700"],
});

const geistSecondary = Great_Vibes({
  variable: "--font-great-vibes",
  subsets: ["latin"],
  weight: "400",
});

export const metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default async function RootLayout({ children }) { 
  await connectDB(); 

  const [regulationsRaw] = await Promise.all([
    Regulation.find({}).lean(),
  ]);

    const regulations = regulationsRaw.map((p) => ({
      ...p,
      _id: p._id.toString(),
      createdAt: p.createdAt?.toISOString(),
      updatedAt: p.updatedAt?.toISOString(),
    }));

  return (
    <html lang="en">
      <GoogleTagManager gtmId="GTM-TZ44KH95" />
      <body
        className={`${geistPrimary.variable} ${geistSecondary.variable} antialiased`}
      >
        <TooltipProvider>
          <div>
            <Navbar data={regulations}/>
            {children}
            <Toaster />
            <Footer data={regulations}/>
          </div>
        </TooltipProvider>
      </body>
    </html>
  );
}
